"""SNAPHU phase-unwrapping pipeline using SNAP GPT and Windows."""

import logging
import re
import shlex
import subprocess
from dataclasses import dataclass
from pathlib import Path
from xml.etree import ElementTree as ET

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class PhaseUnwrappingResult:
    export_directory: Path
    snaphu_config: Path
    unwrapped_header: Path
    unwrapped_product: Path


def _run_command(
    command: list[str],
    *,
    cwd: Path | None = None,
) -> None:
    logger.info("Executing: %s", subprocess.list2cmdline(command))

    subprocess.run(
        command,
        cwd=cwd,
        check=True,
    )


def _find_one(
    directory: Path,
    pattern: str,
) -> Path:
    matches = sorted(directory.rglob(pattern))

    if len(matches) != 1:
        raise RuntimeError(
            f"Expected exactly one {pattern!r} in {directory}, "
            f"found {len(matches)}: {matches}"
        )

    return matches[0]


def _extract_snaphu_command(config_file: Path) -> list[str]:
    """Read the SNAPHU command generated by SNAP."""
    content = config_file.read_text(encoding="utf-8-sig")

    for line in content.splitlines():
        candidate = line.strip().lstrip("#").strip()

        if re.match(r"^snaphu(?:\.exe)?\s+", candidate, re.IGNORECASE):
            arguments = shlex.split(candidate, posix=False)

            if "-f" not in arguments:
                raise ValueError(f"SNAPHU command has no -f argument: {candidate}")

            return arguments

    raise RuntimeError(f"SNAPHU execution command not found in {config_file}")


def _create_import_graph(
    wrapped_product: Path,
    unwrapped_header: Path,
    target_product: Path,
    graph_file: Path,
    *,
    keep_wrapped: bool,
) -> None:
    """Create a SNAP graph with two source products."""
    graph = ET.Element("graph", id="SnaphuImportGraph")
    ET.SubElement(graph, "version").text = "1.0"

    for node_id, source in (
        ("ReadWrapped", wrapped_product),
        ("ReadUnwrapped", unwrapped_header),
    ):
        node = ET.SubElement(graph, "node", id=node_id)
        ET.SubElement(node, "operator").text = "Read"

        parameters = ET.SubElement(node, "parameters")
        ET.SubElement(parameters, "file").text = str(source)

    import_node = ET.SubElement(graph, "node", id="SnaphuImport")
    ET.SubElement(import_node, "operator").text = "SnaphuImport"

    sources = ET.SubElement(import_node, "sources")
    ET.SubElement(sources, "sourceProducts").text = "ReadWrapped,ReadUnwrapped"

    parameters = ET.SubElement(import_node, "parameters")
    ET.SubElement(parameters, "doNotKeepWrapped").text = str(not keep_wrapped).lower()

    write_node = ET.SubElement(graph, "node", id="Write")
    ET.SubElement(write_node, "operator").text = "Write"

    sources = ET.SubElement(write_node, "sources")
    ET.SubElement(sources, "sourceProduct", refid="SnaphuImport")

    parameters = ET.SubElement(write_node, "parameters")
    ET.SubElement(parameters, "file").text = str(target_product)
    ET.SubElement(parameters, "formatName").text = "BEAM-DIMAP"

    ET.indent(graph, space="  ")

    ET.ElementTree(graph).write(
        graph_file,
        encoding="utf-8",
        xml_declaration=True,
    )


def run_phase_unwrapping(
    *,
    filtered_product: str | Path,
    output_directory: str | Path,
    gpt: str | Path,
    snaphu_executable: str | Path,
    stat_cost_mode: str = "DEFO",
    init_method: str = "MST",
    tile_rows: int = 4,
    tile_cols: int = 8,
    row_overlap: int = 200,
    col_overlap: int = 200,
    processors: int = 4,
    tile_cost_threshold: int = 500,
    keep_wrapped: bool = True,
) -> PhaseUnwrappingResult:
    """Export, unwrap, and import a filtered Sentinel-1 interferogram."""

    filtered_product = Path(filtered_product).resolve()
    output_directory = Path(output_directory).resolve()
    gpt = Path(gpt).resolve()
    snaphu_executable = Path(snaphu_executable).resolve()

    if not filtered_product.is_file():
        raise FileNotFoundError(filtered_product)

    if not gpt.is_file():
        raise FileNotFoundError(gpt)

    if not snaphu_executable.is_file():
        raise FileNotFoundError(snaphu_executable)

    if tile_rows < 1 or tile_cols < 1 or processors < 1:
        raise ValueError("Tile counts and processors must be positive.")

    output_directory.mkdir(parents=True, exist_ok=True)

    export_directory = output_directory / "snaphu_export"
    export_directory.mkdir(parents=True, exist_ok=True)

    # 1. Export
    logger.info("Exporting filtered interferogram for SNAPHU")

    export_command = [
        str(gpt),
        "SnaphuExport",
        f"-Ssource={filtered_product}",
        f"-PtargetFolder={export_directory}",
        f"-PstatCostMode={stat_cost_mode}",
        f"-PinitMethod={init_method}",
        f"-PnumberOfTileRows={tile_rows}",
        f"-PnumberOfTileCols={tile_cols}",
        f"-ProwOverlap={row_overlap}",
        f"-PcolOverlap={col_overlap}",
        f"-PnumberOfProcessors={processors}",
        f"-PtileCostThreshold={tile_cost_threshold}",
    ]

    _run_command(export_command)

    config_file = _find_one(export_directory, "snaphu.conf")

    # 2. Execute SNAPHU
    logger.info("Running SNAPHU: %s", config_file)

    snaphu_command = _extract_snaphu_command(config_file)
    snaphu_command[0] = str(snaphu_executable)

    _run_command(
        snaphu_command,
        cwd=config_file.parent,
    )

    unwrapped_header = _find_one(
        export_directory,
        "UnwPhase*.hdr",
    )

    unwrapped_image = unwrapped_header.with_suffix(".img")

    if not unwrapped_image.is_file():
        raise FileNotFoundError(f"SNAPHU image not found: {unwrapped_image}")

    # 3. Import
    logger.info("Importing unwrapped phase into SNAP")

    target_product = output_directory / "unwrapped_interferogram.dim"
    graph_file = output_directory / "snaphu_import_graph.xml"

    _create_import_graph(
        wrapped_product=filtered_product,
        unwrapped_header=unwrapped_header,
        target_product=target_product,
        graph_file=graph_file,
        keep_wrapped=keep_wrapped,
    )

    _run_command(
        [
            str(gpt),
            str(graph_file),
            "-q",
            "2",
        ]
    )

    if not target_product.is_file():
        raise FileNotFoundError(f"SNAP unwrapped product not found: {target_product}")

    logger.info(
        "Phase unwrapping completed: %s",
        target_product,
    )

    return PhaseUnwrappingResult(
        export_directory=export_directory,
        snaphu_config=config_file,
        unwrapped_header=unwrapped_header,
        unwrapped_product=target_product,
    )
